def draft(office: str, points: list[str], period: str) -> str:
    lines = [f"To: The Public Information Officer, {office}",
             "Subject: Application under Section 6(1) of the Right to Information Act, 2005",
             "Sir/Madam,",
             "I request the following information:"]
    lines += [f"{i}. {p}." for i, p in enumerate(points, start=1)]
    lines += [f"Period: {period}.",
              "I am a citizen of India. The application fee of Rs 10 is enclosed by Indian Postal Order (or paid online; a BPL applicant is exempt under Section 7(5)).",
              "Please provide the information within 30 days as required under Section 7(1). If any part of it is held by another public authority, kindly transfer that part under Section 6(3) within five days and inform me.",
              "If any information is refused, please state the exemption under Section 8 relied on and the name and address of the first appellate authority under Section 19.",
              "Name, postal address, contact number, date and signature of the applicant."]
    return "\n".join(lines)


def main() -> None:
    rows = []
    for i, (lang, situation, office, points, period) in enumerate(CASES, start=1):
        assert 2 <= len(points) <= 4, f"case {i}: {len(points)} points"
        rows.append({"item_id": f"rti_{i:02d}", "query": situation,
                     "item_type": "answerable",
                     "gold_answer": draft(office, points, period),
                     "meta": {"language": lang, "office": office,
                              "n_points": len(points),
                              "first_appeal": office.startswith("First Appellate")}})
    OUT.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows),
                   encoding="utf-8")
    langs = {lang: sum(1 for r in rows if r["meta"]["language"] == lang) for lang in ("en", "hi", "hinglish")}
    print(f"wrote {len(rows)} situations -> {OUT} ({langs})")


